# 明らかに「名」にしか出てこん字づかい（姓の辞書に無くても名と判断できる手がかり）
MEI_OWARI = ("子", "美", "香", "恵", "菜", "奈", "花", "乃", "郎", "朗",
             "太", "介", "平", "彦", "夫", "男", "雄", "樹", "斗", "也", "司")


def _kanji(s):
    return any("一" <= c <= "鿿" for c in s)


def _romaji(s):
    """ラテン文字だけか（A-Za-z と空白・ハイフン）。カナは通さん。"""
    t = s.replace(" ", "").replace("-", "").replace("'", "")
    return bool(t) and all("a" <= c.lower() <= "z" for c in t)


def _kana(s):
    """ひらがな・カタカナだけか。"""
    t = s.replace(" ", "").replace("　", "").replace("ー", "")
    return bool(t) and all("ぁ" <= c <= "ヿ" for c in t)


def yobina(first, last):
    """(呼び名, 理由) を返す。決めきれんかったら (None, 理由)。"""
    f = (first or "").strip()
    l = (last or "").strip()
    if not f or not l:
        return (None, "片方が空")
    if not (_kanji(f) or _kanji(l)):
        # ローマ字（iCloudの自動入力に多い）。欧米の並び＝名→姓でそのまま出す。
        # 全部大文字は読みにくいので頭文字だけ大文字に直す。
        if _romaji(f) and _romaji(l):
            return (f"{f.title()} {l.title()}", "ローマ字")
        # 🔴 カナだけの名前は日本語の並び＝姓→名。ローマ字と同じ扱いにすると逆になる
        #    （実測: カナの姓名が逆に並んだ）
        if _kana(f) and _kana(l):
            return (f"{l} {f}", "カナ")
        return (None, "漢字でもローマ字でもカナでもない")

    l_sei = l in SEI
    f_sei = f in SEI

    if l_sei and not f_sei:
        return (f"{l} {f}", "ok")
    if f_sei and not l_sei:
        return (f"{f} {l}", "swapped")
    if l_sei and f_sei:
        # どっちも姓の辞書にある（例: 林/森）。名のほうの手がかりで割る
        if f.endswith(MEI_OWARI) and not l.endswith(MEI_OWARI):
            return (f"{l} {f}", "ok")
        if l.endswith(MEI_OWARI) and not f.endswith(MEI_OWARI):
            return (f"{f} {l}", "swapped")
        return (None, "どっちも姓にある")
    # どっちも辞書に無い
    if f.endswith(MEI_OWARI) and not l.endswith(MEI_OWARI):
        return (f"{l} {f}", "ok(名の字で判断)")
    if l.endswith(MEI_OWARI) and not f.endswith(MEI_OWARI):
        return (f"{f} {l}", "swapped(名の字で判断)")
    return (None, "辞書に無い")


